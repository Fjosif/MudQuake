import { chromium } from '@playwright/test';
const label = process.argv.includes('--before') ? 'before' : 'after';
const browser = await chromium.launch({ channel: 'msedge', headless: true });
const page = await browser.newPage({ viewport: { width: 1912, height: 948 } });
const errors = [];
page.on('pageerror', e => errors.push(e.message));
page.on('console', e => { if (e.type() === 'error') errors.push(e.text()); });
await page.goto('http://127.0.0.1:4173/');
await page.waitForFunction(() => window.mudquake?.ready, { timeout: 90000 });
await page.mouse.move(950, 400); await page.mouse.down(); await page.mouse.move(950, 550, { steps: 12 }); await page.mouse.up();
await page.waitForTimeout(500);
await page.screenshot({ path: `verification/water-${label}-calm.png` });
await page.locator('#quake').click();
await page.waitForFunction(() => window.mudquake.getState().elapsedTime >= 12);
await page.screenshot({ path: `verification/water-${label}-quake.png` });
await page.waitForFunction(() => window.mudquake.getState().elapsedTime >= 20);
await page.screenshot({ path: `verification/water-${label}-aftermath.png` });
await page.mouse.move(950, 450); await page.mouse.down(); await page.mouse.move(1350, 520, { steps: 15 }); await page.mouse.up();
await page.keyboard.down('KeyD'); await page.waitForTimeout(1600); await page.keyboard.up('KeyD');
await page.screenshot({ path: `verification/water-${label}-walking.png` });
console.log(JSON.stringify({ label, errors, state: await page.evaluate(() => window.mudquake.getState()) }));
await browser.close();
if (errors.length) process.exitCode = 1;
